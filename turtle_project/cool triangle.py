import turtle
window = turtle.Screen()
window.setup(500, 500)
tina = turtle.Turtle()
tina.width(3)
tina.color('#DE9518')
tina.penup()
tina.forward(100)
tina.right(90)
tina.forward(86.61)
tina.setheading(90)
tina.pendown()
# print(tina.pos())
for i in range(3):
    tina.circle(int(100), 180)
    tina.left(60)
    # print(tina.pos())
window.listen()
window.mainloop()
