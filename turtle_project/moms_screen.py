import turtle
turtle.setup(500,500)
window = turtle.Screen()
window.setup(width=1.0, height=1.0, startx=None, starty=None)
window.bgcolor("blue")
ben = turtle.Turtle()
window.colormode(255)
ben.fillcolor((210, 180, 140))
ben.speed("fastest")
ben.hideturtle()

def square():
    ben.penup()
    ben.goto(0, 0)
    ben.goto(674, 352)
    ben.pendown()
    ben.setheading(270)
    ben.forward(704)
    ben.right(90)
    ben.forward(1348)
    ben.right(90)
    ben.forward(704)
    ben.right(90)
    ben.forward(1348)
    ben.penup()
    ben.goto(0, 0)
    ben.pendown()
