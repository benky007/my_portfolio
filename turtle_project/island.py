def curve(fraction_of_circle, length_step, angle_step_left, angle_step_right):
    b = length_step
    c = angle_step_left
    d = angle_step_right
    a = fraction_of_circle
    for i in range(a):
        ben.forward(b)
        ben.left(c)
        ben.right(d)


